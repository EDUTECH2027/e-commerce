export const MESSAGES: Record<Lang, Messages> = { en, fr, ar }

export type Vars = Record<string, string | number>

/** Looks a string up in the given language and fills {placeholders}. Usable outside React. */
export function translate(lang: Lang, key: MessageKey, vars?: Vars): string {
  const text = MESSAGES[lang][key] ?? MESSAGES.en[key]
  return vars ? text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : text
}
